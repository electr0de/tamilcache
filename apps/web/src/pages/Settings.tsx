import { useQuery } from '@tanstack/react-query';
import { useEffect, useState } from 'react';
import { api, ensureApiKey, getApiKey } from '../api.js';
import { ErrorNote } from '../components/ui.js';

export function Settings() {
  const [key, setKey] = useState(getApiKey());
  const [revealed, setRevealed] = useState(false);
  const [copied, setCopied] = useState(false);
  const forums = useQuery({ queryKey: ['forums'], queryFn: api.forums });

  useEffect(() => {
    if (key) return;
    void ensureApiKey().then((resolved) => {
      if (resolved) setKey(resolved);
    });
  }, [key]);

  const origin = window.location.origin;
  const torznabUrl = `${origin}/api/v1`;
  const [copiedUrl, setCopiedUrl] = useState(false);

  async function copy() {
    await navigator.clipboard.writeText(key);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  }

  async function copyUrl() {
    await navigator.clipboard.writeText(torznabUrl);
    setCopiedUrl(true);
    setTimeout(() => setCopiedUrl(false), 1500);
  }

  return (
    <div className="max-w-3xl space-y-8">
      <section className="space-y-2">
        <h1 className="text-lg font-semibold">API key</h1>
        <p className="text-xs text-neutral-500">
          Generated by the app on first start and stored in the indexer database — you never type it. Paste it
          into Radarr/Sonarr, or copy the Torznab URL below.
        </p>
        <div className="flex flex-wrap items-center gap-2">
          <code
            data-testid="api-key"
            className="w-96 overflow-hidden text-ellipsis rounded border border-neutral-800 bg-neutral-950 px-3 py-1.5 font-mono text-sm text-neutral-200"
          >
            {key ? (revealed ? key : `${key.slice(0, 6)}${'•'.repeat(18)}`) : 'not resolved yet'}
          </code>
          <button
            type="button"
            onClick={() => setRevealed((value) => !value)}
            className="rounded bg-neutral-800 px-3 py-1.5 text-sm hover:bg-neutral-700"
          >
            {revealed ? 'hide' : 'reveal'}
          </button>
          <button
            type="button"
            onClick={() => void copy()}
            className="rounded bg-neutral-800 px-3 py-1.5 text-sm hover:bg-neutral-700"
          >
            {copied ? 'copied' : 'Copy key'}
          </button>
          <button
            type="button"
            onClick={() => void copyUrl()}
            className="rounded bg-neutral-800 px-3 py-1.5 text-sm hover:bg-neutral-700"
          >
            {copiedUrl ? 'copied' : 'Copy Torznab URL'}
          </button>
        </div>
        <ErrorNote error={forums.error} />
      </section>

      <section className="space-y-2">
        <h2 className="text-sm font-semibold text-neutral-300">Add to Prowlarr / Radarr / Sonarr</h2>
        <code data-testid="torznab-url" className="block truncate rounded bg-neutral-900 px-2 py-1 font-mono text-xs text-neutral-300">
          {torznabUrl}
        </code>
        <dl className="space-y-1 text-xs text-neutral-400">
          <Row label="Indexer type" value="Torznab" />
          <Row label="URL" value={torznabUrl} />
          <Row label="API key" value={key ? `${key.slice(0, 6)}…` : '…'} />
          <Row label="Categories" value="2040 (Movies/SD) · 5030 (TV/HD)" />
        </dl>
        <p className="text-xs text-neutral-600">
          From another container use <code className="text-neutral-400">http://host.docker.internal:8484/api/v1</code>{' '}
          instead of <code className="text-neutral-400">localhost</code>.
        </p>
      </section>


      <section className="space-y-2">
        <h2 className="text-sm font-semibold text-neutral-300">In-scope forums ({forums.data?.length ?? 0})</h2>
        <div className="flex flex-wrap gap-1.5">
          {(forums.data ?? []).map((forum) => (
            <span key={forum.id} className="rounded bg-neutral-900 px-2 py-1 text-[11px] text-neutral-400">
              <span data-testid="forum-name">{forum.name}</span>{' '}
              <span className="text-neutral-600">· {forum.language ?? 'unknown'}</span>
            </span>
          ))}
        </div>
      </section>
    </div>
  );
}

function Row({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex gap-3">
      <dt className="w-32 shrink-0 text-neutral-600">{label}</dt>
      <dd className="font-mono text-neutral-300">{value}</dd>
    </div>
  );
}
